def main():
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    total_filled = 0

    for paper in data:
        pid = paper.get('id')

        # 选择对应的解析
        if pid == 'cet4-2023-12-1':
            explanations = EXPLANATIONS_2023_12_1
        elif pid == 'cet4-2022-06-1':
            explanations = EXPLANATIONS_2022_06_1
        else:
            continue

        filled = 0
        for section in paper.get('sections', []):
            for q in section.get('questions', []):
                qid = q.get('id')
                if qid in explanations and (not q.get('explanation') or q.get('explanation') == '暂无解析'):
                    q['explanation'] = explanations[qid]
                    filled += 1

        print(f"Filled {filled} explanations for {pid}")
        total_filled += filled

    print(f"\nTotal: {total_filled} explanations filled")

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

if __name__ == '__main__':
    main()
