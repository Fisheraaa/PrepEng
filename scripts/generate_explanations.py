def main():
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    total_filled = 0

    for paper in data:
        pid = paper.get('id')

        if pid == 'cet4-2025-06-2':
            explanations = EXPLANATIONS_2025_06_2
        elif pid == 'cet4-2025-06-3':
            explanations = EXPLANATIONS_2025_06_3
        else:
            continue

        filled = 0
        for section in paper.get('sections', []):
            for q in section.get('questions', []):
                qid = q.get('id')
                if qid in explanations:
                    q['explanation'] = explanations[qid]
                    filled += 1

        print(f"Filled {filled} explanations for {pid}")
        total_filled += filled

    print(f"\nTotal: {total_filled} explanations filled")

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

if __name__ == '__main__':
    main()
